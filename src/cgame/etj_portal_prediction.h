#pragma once

#include <array>
#include <optional>

#include "../game/q_shared.h"
#include "../game/etj_portalgun_shared.h"

namespace ETJump {
/*
 * Client-side predicted portal spawning.
 *
 * The server is the authority on portal spawning, but waiting for a round trip
 * before a fired portal exists makes the portal gun feel laggy online. Instead,
 * the client detects portal gun fire events during player state prediction,
 * and spawns a temporary local portal for each unacknowledged shot.
 *
 * The set of predicted portals is rebuilt on every prediction run, while
 * replaying the unacknowledged user commands in order. This gives us two
 * important properties for free:
 *
 * - Time correctness: a portal only exists for the commands that come after
 *   the command that fired it, so re-predicting older commands can never
 *   interact with a portal that didn't exist yet at that point.
 *
 * - Reconciliation: once the server has processed the command that fired a
 *   portal, the command is no longer replayed, so the predicted portal
 *   disappears on the same frame the snapshot containing the server's
 *   result (the real portal, or no portal if it was rejected) becomes active.
 *
 * While a predicted portal exists, it supersedes our own server portal
 * of the same color (which the server will free once it processes the shot).
 */
class PortalPrediction {
public:
  PortalPrediction() = default;
  ~PortalPrediction() = default;

  // called before replaying user commands in 'CG_PredictPlayerState'
  void beginPrediction();
  // called after replaying user commands in 'CG_PredictPlayerState'
  void endPrediction();
  // called when player state prediction does not run
  // (demo playback, spectating, 'cg_nopredict')
  void clear();

  // called for each replayed command, after trigger prediction,
  // detects portal gun fire events generated by the command
  void checkFire(const playerState_t &before, const playerState_t &after,
                 const usercmd_t &cmd);

  // true if predicted portals are active this frame
  [[nodiscard]] bool isActive() const;

  // Resolves the state to use for a portal entity in the snapshot during
  // trigger prediction. Returns false if the portal is superseded by a
  // predicted portal, otherwise 'out' holds the entity state with
  // its destination adjusted for predicted portals.
  bool resolveServerPortal(const entityState_t &es, entityState_t &out) const;

  // true if the snapshot portal entity should not be drawn,
  // because a predicted portal supersedes it
  [[nodiscard]] bool isSuperseded(const entityState_t &es) const;

  // spawn time to use for the spawning animation of a snapshot portal entity,
  // so the animation continues from the predicted portal it replaced
  [[nodiscard]] int32_t spawnAnimTime(const entityState_t &es) const;

  // calls 'func' for each active predicted portal, with its entity state
  // (destination included) and the time it was last debug drawn
  template <typename Func> void forEachPortal(Func &&func) {
    for (auto &portal : portals) {
      entityState_t es{};

      if (!resolvePredictedPortal(portal, es)) {
        continue;
      }

      func(es, portal->lastRailboxTime);
    }
  }

  // adds predicted portals to the scene
  void addToScene();

private:
  struct PredictedPortal {
    // command time of the command that fired the portal
    int32_t fireTime{};
    // entity the portal is attached to
    int32_t parentEntityNum = ENTITYNUM_NONE;
    // portal entity state, as the server would send it,
    // minus the destination, which is resolved on demand
    entityState_t es{};
    // for 'etj_portalDebug'
    int32_t lastRailboxTime{};
  };

  struct ConfirmedPortal {
    int32_t eType{};
    vec3_t origin{};
    int32_t spawnTime{};
  };

  static constexpr int32_t NUM_PORTAL_TYPES = 2;

  [[nodiscard]] static int32_t typeIndex(int32_t eType);
  [[nodiscard]] static int32_t otherType(int32_t eType);
  [[nodiscard]] bool isOwnPortal(const entityState_t &es) const;

  // false if the portal would've been removed by the server,
  // e.g. the 'func_static_client' it was attached to was toggled off
  [[nodiscard]] bool isAlive(const PredictedPortal &portal) const;

  // returns the predicted portal of given type, if one exists and is alive
  [[nodiscard]] const PredictedPortal *getPortal(int32_t eType) const;

  // looks up where our portal of the given type is,
  // taking predicted portals into account
  bool getOwnPortalPosition(int32_t eType, vec3_t origin,
                            vec3_t angles) const;

  bool resolvePredictedPortal(const std::optional<PredictedPortal> &portal,
                              entityState_t &out) const;

  // runs the portal gun trace & placement logic, same as server
  bool tryPlacePortal(const playerState_t &ps, int32_t eType,
                      PortalgunShared::Placement &placement,
                      int32_t &hitEntityNum) const;

  [[nodiscard]] bool
  overlapsOtherPortals(const PortalgunShared::Placement &placement,
                       int32_t eType) const;

  bool active{};
  int32_t clientNum{};

  // predicted portals, indexed by 'typeIndex'
  std::array<std::optional<PredictedPortal>, NUM_PORTAL_TYPES> portals{};
  // predicted portals from the previous prediction run,
  // so we can keep the placement & spawn time consistent between frames
  std::array<std::optional<PredictedPortal>, NUM_PORTAL_TYPES> prevPortals{};
  // our own portals in the current snapshot
  std::array<std::optional<entityState_t>, NUM_PORTAL_TYPES> serverPortals{};
  // predicted portals that were acknowledged by the server
  std::array<std::optional<ConfirmedPortal>, NUM_PORTAL_TYPES>
      confirmedPortals{};

  // fire time of the last shot we drew a trail for
  int32_t lastTrailFireTime{};
};
} // namespace ETJump
